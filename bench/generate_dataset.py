#!/usr/bin/env python3
"""Generate a labelled alert dataset for measuring triage.

Real SOC data cannot be published, and synthetic data generated by the same
person who wrote the scorer is suspect. So the generator is deliberately
dumb and documented: it draws from a fixed menu of scenarios with a seed, and
every alert carries a ground-truth label that triage never sees:

  attack   part of a real multi-stage intrusion (the thing we must rank first)
  benign   an authorised vulnerability scanner, a flapping signature, a
           misconfigured client: things that fire alerts and are not attacks

The evaluation question is then simple: does triage put the attacks on top
and the benign noise at the bottom, and how much does it collapse the volume.

Usage:
    python bench/generate_dataset.py --days 7 --seed 42 --out bench/data/week.json
"""

from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timedelta
from pathlib import Path

ATTACK_CHAINS = [
    # (signature, severity, technique) in order. Gaps of 1 to 6 minutes.
    [("Nmap service scan", "low", "T1046"), ("SQL injection attempt", "high", "T1190"),
     ("Web shell upload", "critical", "T1059"), ("Credential dumping tool", "critical", "T1003"),
     ("Large outbound transfer", "high", "T1041")],
    [("Brute force SSH login", "medium", "T1110"), ("Successful login after failures", "high", "T1078"),
     ("Sudo privilege escalation", "high", "T1548"), ("Cron persistence added", "high", "T1053"),
     ("DNS tunnelling pattern", "high", "T1071")],
    [("Phishing attachment opened", "medium", "T1566"), ("Office spawns PowerShell", "high", "T1059"),
     ("LSASS memory access", "critical", "T1003"), ("SMB lateral movement", "high", "T1021"),
     ("Ransomware file rename burst", "critical", "T1486")],
    [("Public app exploit attempt", "high", "T1190"), ("Reverse shell beacon", "critical", "T1071"),
     ("Local account created", "medium", "T1136"), ("Registry run key added", "medium", "T1547")],
]

BENIGN_PATTERNS = {
    # authorised scanner: lots of recon on many hosts, nothing else
    "vuln_scanner": [("Nmap service scan", "low", "T1046"), ("Nessus plugin probe", "low", "T1595"),
                     ("Nikto user agent", "low", "T1595")],
    # one signature that flaps for an hour on one host
    "flapping_sig": [("Suspicious TLS SNI", "medium", ""), ("Suspicious TLS SNI", "medium", "")],
    # a misconfigured client hammering auth
    "misconfig_auth": [("Brute force SSH login", "medium", "T1110")],
    # backup job that looks like exfil
    "backup_job": [("Large outbound transfer", "high", "T1041")],
}

HOSTS = [f"web-{i:02d}" for i in range(1, 6)] + [f"db-{i:02d}" for i in range(1, 3)] + \
        [f"ws-{i:03d}" for i in range(1, 21)] + ["dc-01", "jump-01"]
EXTERNAL_IPS = [f"203.0.113.{i}" for i in range(2, 60)] + [f"198.51.100.{i}" for i in range(2, 60)]
SCANNER_IP = "10.0.9.9"


def gen(days: int, seed: int, attacks_per_day: float, noise_per_day: int):
    rng = random.Random(seed)
    start = datetime(2026, 9, 1)
    alerts = []
    truth = {"attack": 0, "benign": 0, "campaigns": []}

    def add(ts, host, sig, sev, tech, src, label, campaign=""):
        alerts.append({
            "timestamp": ts.strftime("%Y-%m-%dT%H:%M:%S"), "host": host, "signature": sig,
            "severity": sev, "technique_id": tech, "src_ip": src, "dst_ip": "10.0.0." + str(rng.randint(2, 250)),
            "label": label, "campaign": campaign,
        })
        truth[label] += 1

    for d in range(days):
        day = start + timedelta(days=d)
        # attacks
        n_attacks = sum(1 for _ in range(3) if rng.random() < attacks_per_day / 3)
        for k in range(n_attacks):
            chain = rng.choice(ATTACK_CHAINS)
            host = rng.choice(HOSTS)
            src = rng.choice(EXTERNAL_IPS)
            t = day + timedelta(hours=rng.randint(0, 23), minutes=rng.randint(0, 59))
            cid = f"ATK-{d:02d}-{k}"
            truth["campaigns"].append(cid)
            # a chain may hop to a second host (lateral movement)
            hop_at = rng.randint(2, len(chain) - 1) if rng.random() < 0.4 else None
            for i, (sig, sev, tech) in enumerate(chain):
                h = rng.choice(HOSTS) if (hop_at is not None and i >= hop_at) else host
                add(t, h, sig, sev, tech, src, "attack", cid)
                t += timedelta(minutes=rng.randint(1, 6))
                # some stages fire twice
                if rng.random() < 0.3:
                    add(t, h, sig, sev, tech, src, "attack", cid)
                    t += timedelta(minutes=1)
        # benign noise
        for _ in range(noise_per_day):
            kind = rng.choice(list(BENIGN_PATTERNS))
            pats = BENIGN_PATTERNS[kind]
            t = day + timedelta(hours=rng.randint(0, 23), minutes=rng.randint(0, 59))
            if kind == "vuln_scanner":
                for h in rng.sample(HOSTS, rng.randint(5, 12)):
                    sig, sev, tech = rng.choice(pats)
                    add(t, h, sig, sev, tech, SCANNER_IP, "benign", kind)
                    t += timedelta(seconds=rng.randint(5, 40))
            elif kind == "flapping_sig":
                h = rng.choice(HOSTS)
                for _ in range(rng.randint(8, 25)):
                    sig, sev, tech = pats[0]
                    add(t, h, sig, sev, tech, rng.choice(EXTERNAL_IPS), "benign", kind)
                    t += timedelta(minutes=rng.randint(1, 4))
            elif kind == "misconfig_auth":
                h = rng.choice(HOSTS)
                src = "10.0.5." + str(rng.randint(2, 50))
                for _ in range(rng.randint(5, 15)):
                    sig, sev, tech = pats[0]
                    add(t, h, sig, sev, tech, src, "benign", kind)
                    t += timedelta(minutes=rng.randint(1, 3))
            else:  # backup_job
                sig, sev, tech = pats[0]
                add(t, rng.choice(HOSTS[:7]), sig, sev, tech, "10.0.2.2", "benign", kind)

    alerts.sort(key=lambda a: a["timestamp"])
    return alerts, truth


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=7)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--attacks-per-day", type=float, default=1.5)
    ap.add_argument("--noise-per-day", type=int, default=6)
    ap.add_argument("--out", default="bench/data/week.json")
    a = ap.parse_args()
    alerts, truth = gen(a.days, a.seed, a.attacks_per_day, a.noise_per_day)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("[\n" + ",\n".join(json.dumps(a, separators=(",", ":")) for a in alerts) + "\n]\n")
    # triage ignores unknown fields, so the labels ride along in the same file.
    print(f"{len(alerts)} alerts ({truth['attack']} attack, {truth['benign']} benign, "
          f"{len(truth['campaigns'])} campaigns) -> {out}")


if __name__ == "__main__":
    main()
